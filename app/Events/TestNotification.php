    }

    public function via($notifiable)
    {
        // Only using database and broadcast channels as specified in requirements
        return ['broadcast'];
    }
    /**
     * Get the channels the event should broadcast on.
     *
     * @return array<int, \Illuminate\Broadcasting\Channel>
